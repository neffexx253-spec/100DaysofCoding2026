public class Main {
    public static void main(String[] args) {
        // Float (pakai f di akhir)
        float tinggibadan = 163.0f;

        // Double (tanpa akhiran)
        double beratbadan = 61.0;

        // Operasi sederhana
        tinggibadan = tinggibadan + 2.5f;
        beratbadan = beratbadan + 2.5;

        // Cetak hasil
        System.out.println("Float " + "Tinggi Badan:" + tinggibadan + " " + "cm");
        System.out.println("Double " + " Berat Badan:" + beratbadan + " " + "kg");
    }
}
